//! Hierarchical Predictive Self-Modeling — multi-timescale prediction loop.
//!
//! Pulses generate structured predictions before each cognitive cycle, then
//! resolve them against actual outcomes to compute "surprise" scores.
//! Prediction errors drive attention allocation and pipeline graduation.
//!
//! # What this is NOT (vs. Active Inference)
//!
//! Earlier drafts framed this as "Active Inference." That label was wrong.
//! Friston/Parr/Pezzulo-style active inference requires a persistent
//! generative model with explicit priors and likelihoods, free-energy
//! minimization as the unified objective, expected-free-energy-driven
//! policy selection, and precision (inverse-variance) weighting on
//! prediction errors. **None of those are present here.**
//!
//! This module implements the more pragmatic shape from Clark (2015,
//! *Surfing Uncertainty*): a hierarchical prediction-and-error-tracking
//! loop, applied to the pulse's own cognitive trajectory rather than to
//! perceptual inputs. Surprise is generated by LLM self-assessment in
//! the resolve step, not by a learned generative model with calibrated
//! priors. We track surprise; we do not minimize free energy.
//!
//! See `continuous-entity-process-spec.md` Phase 2 for the full rationale.
//!
//! # Architecture
//!
//! The prediction stack holds predictions at three timescales:
//! - **Cycle**: within a single 20-minute cognitive cycle
//! - **Session**: across a conversation session
//! - **Weekly**: longer-term trends and patterns
//!
//! Each prediction has a self-assessed confidence level. When resolved, a
//! surprise score (0.0 = perfectly predicted, 1.0 = maximally surprising)
//! and error direction are recorded. High-surprise errors bubble up as
//! unprocessed `PredictionError`s, which the prompt builder surfaces back
//! to the pulse in the next turn.

