//! The prediction store — a read-only record of past predictions and their
//! errors (PN-133).
//!
//! Pulses once wrote free-form predictions in their cycles and resolved them
//! with a self-assessed "surprise" score. Phase 0 retired that: open
//! predictions are voided at boot, markers are refused, and the only reader
//! left is the tension substrate, which opens threads for recorded errors.
//! The sections below describe the model the data was written under.
//!
//! # What this is NOT (vs. Active Inference)
//!
//! Earlier drafts framed this as "Active Inference." That label was wrong.
//! Friston/Parr/Pezzulo-style active inference requires a persistent
//! generative model with explicit priors and likelihoods, free-energy
//! minimization as the unified objective, expected-free-energy-driven
//! policy selection, and precision (inverse-variance) weighting on
//! prediction errors. **None of those are present here.**
//!
//! This module implements the more pragmatic shape from Clark (2015,
//! *Surfing Uncertainty*): a hierarchical prediction-and-error-tracking
//! loop, applied to the pulse's own cognitive trajectory rather than to
//! perceptual inputs. Surprise is generated by LLM self-assessment in
//! the resolve step, not by a learned generative model with calibrated
//! priors. We track surprise; we do not minimize free energy.
//!
//! See `continuous-entity-process-spec.md` Phase 2 for the full rationale.
//!
//! # Architecture
//!
//! The prediction stack holds predictions at three timescales:
//! - **Cycle**: within a single 20-minute cognitive cycle
//! - **Session**: across a conversation session
//! - **Weekly**: longer-term trends and patterns
//!
//! Each prediction has a self-assessed confidence level. When resolved, a
//! surprise score (0.0 = perfectly predicted, 1.0 = maximally surprising)
//! and error direction are recorded. High-surprise errors bubble up as
//! unprocessed `PredictionError`s.
//!
//! # Frozen since PN-133 (Phase 0)
//!
//! Free-form predictions had no checkable referent, so no production path
//! writes this store any more: markers are refused (`markers`, `refusals`),
//! and the one boot migration [`store::void_open_predictions`] closes every
//! open prediction as [`ErrorDirection::Void`]. What is left is read-only:
//! the types `predictions.json` deserializes into, and the error records the
//! tension substrate still ingests. Writing returns with a checkable
//! prediction kind.

pub mod markers;
pub mod refusals;
pub mod store;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

use crate::config::PredictionConfig;

/// The timescale at which a prediction operates.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Timescale {
    /// Within a single cognitive cycle (~20 minutes).
    Cycle,
    /// Across a conversation session.
    Session,
    /// Longer-term weekly trends.
    Weekly,
}

impl std::fmt::Display for Timescale {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Timescale::Cycle => write!(f, "cycle"),
            Timescale::Session => write!(f, "session"),
            Timescale::Weekly => write!(f, "weekly"),
        }
    }
}

/// How the prediction error relates to the pulse's model of the world.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ErrorDirection {
    /// The pulse was more confident than warranted — reality was messier.
    Overconfident,
    /// The pulse was less confident than warranted — reality was more predictable.
    Underconfident,
    /// The pulse predicted the wrong thing entirely — different dimension of outcome.
    Misdirected,
    /// Something genuinely new happened that the pulse had no model for.
    Novel,
    /// The prediction held: confidence matched the outcome. Not an error
    /// direction — a calibration system that cannot record being right is
    /// measuring the wrong thing (PN-86). A well-calibrated resolution
    /// normally carries low surprise.
    WellCalibrated,
    /// Retired without a verdict: the Phase 0 migration (PN-133) closed every
    /// open free-form prediction this way, because none had a referent that
    /// could be checked. Not evidence of anything — neither a hit nor an
    /// error — and only the runtime writes it.
    Void,
    /// Catch-all for direction values written to disk by a newer release
    /// than this binary (SEC-006). Without it, one unrecognized direction
    /// makes the whole snapshot fail to deserialize, `load` fail-opens to
    /// an empty stack, and the next save erases the pulse's entire
    /// prediction history.
    #[serde(other)]
    Unknown,
}

impl std::fmt::Display for ErrorDirection {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ErrorDirection::Overconfident => write!(f, "overconfident"),
            ErrorDirection::Underconfident => write!(f, "underconfident"),
            ErrorDirection::Misdirected => write!(f, "misdirected"),
            ErrorDirection::Novel => write!(f, "novel"),
            ErrorDirection::WellCalibrated => write!(f, "well-calibrated"),
            ErrorDirection::Void => write!(f, "void"),
            ErrorDirection::Unknown => write!(f, "unknown"),
        }
    }
}

/// The outcome of a resolved prediction.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PredictionResolution {
    /// What actually happened.
    pub actual: String,
    /// How surprising the outcome was (0.0 = perfectly predicted, 1.0 = maximally surprising).
    pub surprise: f64,
    /// How the prediction error relates to the pulse's world model.
    pub direction: ErrorDirection,
    /// Optional insight about what the prediction error reveals.
    pub insight: Option<String>,
}

/// A prediction made by the pulse at a specific timescale.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Prediction {
    /// Unique identifier for this prediction.
    pub id: String,
    /// The timescale this prediction operates at.
    pub timescale: Timescale,
    /// What the pulse predicts will happen.
    pub content: String,
    /// How confident the pulse is in this prediction (0.0 to 1.0).
    pub confidence: f64,
    /// When this prediction was created.
    pub created_at: DateTime<Utc>,
    /// When this prediction was resolved (None if still pending).
    pub resolved_at: Option<DateTime<Utc>>,
    /// The resolution outcome (None if still pending).
    pub resolution: Option<PredictionResolution>,
}

impl Prediction {
    /// Whether this prediction was voided rather than resolved. A void
    /// prediction is closed but is not evidence that anything happened.
    #[must_use]
    pub fn is_void(&self) -> bool {
        self.resolution
            .as_ref()
            .is_some_and(|r| r.direction == ErrorDirection::Void)
    }
}

/// A prediction error — created when a resolved prediction has surprise above threshold.
/// These errors drive the pulse's attention toward what it failed to predict.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PredictionError {
    /// The prediction that generated this error.
    pub prediction_id: String,
    /// The surprise score from the resolution.
    pub surprise: f64,
    /// The direction of the prediction error.
    pub direction: ErrorDirection,
    /// Optional insight about what this error reveals.
    pub insight: Option<String>,
    /// When this error was created.
    pub created_at: DateTime<Utc>,
    /// Whether this error has been marked processed. Nothing marks errors
    /// any more; tension ingest reads the unprocessed ones.
    pub processed: bool,
    /// Snapshot of the prediction's text, taken at resolve time.
    ///
    /// The error record outlived the prediction that produced it: the old
    /// writer's prune evicted resolved predictions while their errors
    /// survived, so a consumer looking `prediction_id` up in the store could
    /// read a hole. The text snapshotted here makes the error self-contained.
    ///
    /// `None` on records written before this field existed.
    #[serde(default)]
    pub predicted: Option<String>,
    /// Snapshot of the resolution's `actual` text, taken at resolve time.
    /// Same rationale and same migration default as [`Self::predicted`].
    #[serde(default)]
    pub actual: Option<String>,
}

/// The prediction stack as read from disk, stamped with the live config.
///
/// Not directly `Serialize`/`Deserialize`. The on-disk format is
/// [`PredictionStackSnapshot`] — `config` lives in `pulse-null.toml`, not
/// the per-pulse JSON snapshot, so any deserializer that produced a
/// `PredictionStack` directly would silently default the config and
/// quietly drift away from `Config::prediction` (M7).
#[derive(Debug, Clone, Default)]
pub struct PredictionStack {
    /// All predictions (pending, resolved and void).
    pub predictions: Vec<Prediction>,
    /// Prediction errors recorded from high-surprise resolutions.
    pub errors: Vec<PredictionError>,
    /// Loaded from `Config::prediction`.
    pub config: PredictionConfig,
}

/// On-disk format for the prediction stack — predictions and errors only.
/// `PredictionStack::config` is intentionally not serialized; the loader
/// rehydrates it from the live `PredictionConfig`.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct PredictionStackSnapshot {
    pub predictions: Vec<Prediction>,
    pub errors: Vec<PredictionError>,
}

impl PredictionStackSnapshot {
    /// Promote a deserialized snapshot into a runtime `PredictionStack`,
    /// stamped with the pulse's live `PredictionConfig`.
    #[must_use]
    pub fn into_stack(self, config: PredictionConfig) -> PredictionStack {
        PredictionStack {
            predictions: self.predictions,
            errors: self.errors,
            config,
        }
    }
}

impl PredictionStack {
    /// An empty stack with the given config — what `store::load` returns
    /// when there is no readable file.
    #[must_use]
    pub fn with_config(config: PredictionConfig) -> Self {
        Self {
            predictions: Vec::new(),
            errors: Vec::new(),
            config,
        }
    }

    /// Iterate over unprocessed prediction errors.
    pub fn unprocessed_errors(&self) -> impl Iterator<Item = &PredictionError> {
        self.errors.iter().filter(|e| !e.processed)
    }
}

/// Raw-JSON `predictions.json` fixtures. Tests build the store the way it
/// sits on disk, since nothing in production writes one any more.
#[cfg(test)]
pub mod fixtures {
    use std::path::Path;

    use serde_json::{json, Value};

    use super::{PredictionStack, PredictionStackSnapshot};
    use crate::config::PredictionConfig;

    /// A pending prediction entry.
    pub fn pending(id: &str, content: &str) -> Value {
        json!({
            "id": id, "timescale": "cycle", "content": content, "confidence": 0.5,
            "created_at": "2026-10-01T00:00:00Z", "resolved_at": null, "resolution": null,
        })
    }

    /// A resolved prediction entry.
    pub fn resolved(
        id: &str,
        content: &str,
        actual: &str,
        surprise: f64,
        direction: &str,
    ) -> Value {
        json!({
            "id": id, "timescale": "cycle", "content": content, "confidence": 0.6,
            "created_at": "2026-10-01T00:00:00Z", "resolved_at": "2026-10-02T00:00:00Z",
            "resolution": {
                "actual": actual, "surprise": surprise, "direction": direction,
                "insight": "an insight",
            },
        })
    }

    /// An unprocessed error record, with the text snapshots the writer took.
    pub fn error(prediction_id: &str, predicted: &str, actual: &str, surprise: f64) -> Value {
        json!({
            "prediction_id": prediction_id, "surprise": surprise, "direction": "overconfident",
            "insight": "freeze detector is blind to soft limits",
            "created_at": "2026-10-02T00:00:00Z", "processed": false,
            "predicted": predicted, "actual": actual,
        })
    }

    /// The whole document.
    pub fn document(predictions: Vec<Value>, errors: Vec<Value>) -> Value {
        json!({ "predictions": predictions, "errors": errors })
    }

    /// Write `predictions.json` into `root`.
    pub fn write_store(root: &Path, doc: &Value) {
        std::fs::write(root.join("predictions.json"), doc.to_string()).unwrap();
    }

    /// The stack `store::load` would produce for `doc`.
    pub fn stack(doc: Value, config: PredictionConfig) -> PredictionStack {
        serde_json::from_value::<PredictionStackSnapshot>(doc)
            .unwrap()
            .into_stack(config)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Records written before the snapshot fields existed lack them in
    /// their error records. They must load, not fail the whole snapshot.
    #[test]
    fn error_record_without_snapshot_fields_deserializes() {
        let legacy = r#"{
            "predictions": [],
            "errors": [{
                "prediction_id": "abc",
                "surprise": 0.5,
                "direction": "misdirected",
                "insight": null,
                "created_at": "2026-08-20T00:00:00Z",
                "processed": false
            }]
        }"#;

        let snapshot: PredictionStackSnapshot = serde_json::from_str(legacy).unwrap();
        assert_eq!(snapshot.errors.len(), 1);
        assert!(snapshot.errors[0].predicted.is_none());
        assert!(snapshot.errors[0].actual.is_none());
    }

    #[test]
    fn timescale_display() {
        assert_eq!(Timescale::Cycle.to_string(), "cycle");
        assert_eq!(Timescale::Session.to_string(), "session");
        assert_eq!(Timescale::Weekly.to_string(), "weekly");
    }

    #[test]
    fn error_direction_display_and_serde() {
        assert_eq!(ErrorDirection::Overconfident.to_string(), "overconfident");
        assert_eq!(
            ErrorDirection::WellCalibrated.to_string(),
            "well-calibrated"
        );
        assert_eq!(ErrorDirection::Void.to_string(), "void");
        assert_eq!(
            serde_json::to_string(&ErrorDirection::Void).unwrap(),
            "\"void\""
        );
        assert_eq!(
            serde_json::from_str::<ErrorDirection>("\"well_calibrated\"").unwrap(),
            ErrorDirection::WellCalibrated
        );
    }

    /// SEC-006: a direction value written by a newer release must not fail
    /// the whole snapshot deserialization — that would fail-open `load` to
    /// an empty stack.
    #[test]
    fn unknown_direction_value_deserializes_to_catch_all() {
        let json = r#"{"predictions":[],"errors":[{"prediction_id":"p1","surprise":0.9,"direction":"some_future_direction","insight":null,"created_at":"2026-08-09T00:00:00Z","processed":false}]}"#;
        let snapshot: PredictionStackSnapshot = serde_json::from_str(json).unwrap();
        assert_eq!(snapshot.errors[0].direction, ErrorDirection::Unknown);
        assert_eq!(ErrorDirection::Unknown.to_string(), "unknown");
    }

    /// The snapshot carries predictions and errors only; rehydrating stamps
    /// the caller's config, never a default (M7).
    #[test]
    fn snapshot_rehydrates_with_the_callers_config() {
        let doc = fixtures::document(
            vec![fixtures::resolved(
                "p-1",
                "will it rain",
                "it rained",
                0.4,
                "overconfident",
            )],
            vec![fixtures::error("p-1", "will it rain", "it rained", 0.4)],
        );
        let custom = PredictionConfig {
            surprise_threshold: 0.95,
            ..PredictionConfig::default()
        };
        let stack = fixtures::stack(doc, custom);
        assert_eq!(stack.predictions.len(), 1);
        assert_eq!(stack.unprocessed_errors().count(), 1);
        assert!((stack.config.surprise_threshold - 0.95).abs() < f64::EPSILON);
        assert!(!stack.predictions[0].is_void());
    }
}
